//! Writes `wr_posix.h`, the C declarations of the layer's exports, from the
//! layer's own signature table. A Rust type with no known C spelling stops
//! the generator, so the header can never drift into a guess.

use std::process::ExitCode;
use wyrmroot_posix::exports::SIGNATURES;

/// Rust spellings (whitespace removed) and their C equivalents.
const TYPES: &[(&str, &str)] = &[
    ("()", "void"),
    ("!", "_Noreturn void"),
    ("c_int", "int"),
    ("c_long", "long"),
    ("c_ulong", "unsigned long"),
    ("u64", "unsigned long"),
    ("usize", "size_t"),
    ("*constusize", "const size_t *"),
    ("*mutc_void", "void *"),
    ("*constc_void", "const void *"),
    ("*mutc_char", "char *"),
    ("*constc_char", "const char *"),
    ("*mutKstat", "struct kstat *"),
    ("*constIovec", "const struct iovec *"),
    ("*mutTimespec", "struct timespec *"),
    ("*constTimespec", "const struct timespec *"),
    ("*mutUtsname", "struct utsname *"),
];

fn c_type(rust: &str) -> Option<&'static str> {
    let compact: String = rust.chars().filter(|c| !c.is_whitespace()).collect();
    TYPES
        .iter()
        .find(|(name, _)| *name == compact)
        .map(|(_, c)| *c)
}

fn main() -> ExitCode {
    let mut out = String::from(
        "/* SPDX-License-Identifier: GPL-3.0-or-later WITH Classpath-exception-2.0 */\n\
         /* Generated by wr-posix-header from wyrmroot-posix. Do not edit. */\n\
         #ifndef WR_POSIX_H\n#define WR_POSIX_H\n\n#include <stddef.h>\n\n\
         struct kstat;\nstruct iovec;\nstruct timespec;\nstruct utsname;\n\n",
    );
    for signature in SIGNATURES {
        let Some(returns) = c_type(signature.returns) else {
            eprintln!("wr-posix-header: no C type for {}", signature.returns);
            return ExitCode::FAILURE;
        };
        let mut arguments = Vec::new();
        for (name, rust) in signature.arguments {
            let Some(c) = c_type(rust) else {
                eprintln!(
                    "wr-posix-header: no C type for {rust} in {}",
                    signature.name
                );
                return ExitCode::FAILURE;
            };
            let separator = if c.ends_with('*') { "" } else { " " };
            arguments.push(format!("{c}{separator}{name}"));
        }
        let arguments = if arguments.is_empty() {
            "void".to_string()
        } else {
            arguments.join(", ")
        };
        out.push_str(&format!("{returns} {}({arguments});\n", signature.name));
    }
    out.push_str("\n#endif\n");
    print!("{out}");
    ExitCode::SUCCESS
}
